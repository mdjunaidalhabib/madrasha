type SidebarText = typeof sidebarText.bn;

/** Translated module label, or the DB label for unknown keys. */
export const sidebarModuleLabel = (t: SidebarText, key: string, dbLabel: string) =>
  t.modules[key] || dbLabel;

/** Translated child label, or the DB label for unknown keys. */
export const sidebarChildLabel = (t: SidebarText, moduleKey: string, childKey: string, dbLabel: string) =>
  t.children[`${moduleKey}/${childKey}`] || t.childFallback[childKey] || dbLabel;
